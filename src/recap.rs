fn string_array(value: &Value, key: &str, limit: usize) -> Vec<String> {
    value
        .get(key)
        .and_then(|v| v.as_array())
        .into_iter()
        .flatten()
        .filter_map(|v| v.as_str())
        .map(clean_one_line)
        .filter(|s| !s.is_empty())
        .take(limit)
        .collect()
}

fn clean_one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn extract_json_object(text: &str) -> Option<&str> {
    let start = text.find('{')?;
    let end = text.rfind('}')?;
    (end >= start).then_some(&text[start..=end])
}

fn redact_sensitive(text: &str) -> String {
    let mut redacted = text.to_string();
    let patterns = [
        r"sk-ant-[A-Za-z0-9_\-]{12,}",
        r"sk-[A-Za-z0-9_\-]{20,}",
        r"github_pat_[A-Za-z0-9_]{20,}",
        r"gh[pousr]_[A-Za-z0-9_]{20,}",
        r"AKIA[0-9A-Z]{16}",
        r#"(?i)(api[_-]?key|token|secret|password)(['"\s:=]+)[A-Za-z0-9_\-./+=]{12,}"#,
    ];
    for pattern in patterns {
        if let Ok(regex) = Regex::new(pattern) {
            redacted = regex.replace_all(&redacted, "$1$2[REDACTED]").to_string();
        }
    }
    redacted
}

fn truncate_start(text: &str, max_chars: usize) -> String {
    let count = text.chars().count();
    if count <= max_chars {
        return text.to_string();
    }
    let keep: String = text.chars().skip(count - max_chars).collect();
    format!(
        "... omitted {} earlier chars ...\n{}",
        count - max_chars,
        keep
    )
}

fn truncate_end(text: &str, max_chars: usize) -> String {
    let count = text.chars().count();
    if count <= max_chars {
        text.to_string()
    } else {
        let kept: String = text.chars().take(max_chars).collect();
        format!("{}...", kept)
    }
}

fn truncate_middle(text: &str, max_chars: usize) -> String {
    let count = text.chars().count();
    if count <= max_chars {
        return text.to_string();
    }
    let marker = "\n... omitted middle ...\n";
    let available = max_chars.saturating_sub(marker.chars().count());
    let head_chars = available / 2;
    let tail_chars = available - head_chars;
    let head: String = text.chars().take(head_chars).collect();
    let tail: String = text.chars().skip(count - tail_chars).collect();
    format!("{head}{marker}{tail}")
}

fn now_unix_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as u64
}

fn recap_age_bucket(generated_at_ms: u64) -> u64 {
    let elapsed_secs = now_unix_ms().saturating_sub(generated_at_ms) / 1000;
    if elapsed_secs < 60 {
        0
    } else {
        elapsed_secs / 60
    }
}

fn write_recap_cache(cwd: &Path, recap: &TurnRecap) -> Result<()> {
    let session_id = std::env::var("CRABIGATOR_SESSION_ID").unwrap_or_default();
    if session_id.is_empty() {
        return Ok(());
    }
    let session_dir = PathBuf::from(format!("/tmp/crabigator-{}", session_id));
    fs::create_dir_all(&session_dir)?;
    let path = session_dir.join("recap.json");
    let tmp_path = path.with_extension("tmp");
    let json = serde_json::to_string_pretty(&json!({
        "cwd": cwd.to_string_lossy(),
        "recap": recap,
    }))?;
    fs::write(&tmp_path, json)?;
    fs::rename(&tmp_path, path)?;
    Ok(())
}

