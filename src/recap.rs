fn is_codex_bootstrap(text: &str) -> bool {
    text.contains("<INSTRUCTIONS>")
        || text.contains("<environment_context>")
        || text.contains("# AGENTS.md instructions")
}

fn push_section(out: &mut String, label: &str, text: &str) {
    let trimmed = text.trim();
    if trimmed.is_empty() {
        return;
    }
    out.push_str("\n[");
    out.push_str(label);
    out.push_str("]\n");
    out.push_str(trimmed);
    out.push('\n');
}

fn format_json_preview(value: &Value) -> String {
    match value {
        Value::String(text) => truncate_end(text, 600),
        other => serde_json::to_string(other)
            .map(|s| truncate_end(&s, 900))
            .unwrap_or_default(),
    }
}

fn build_anthropic_request(
    job: &RecapJob,
    transcript: &TurnTranscript,
    slack_threads: &[SlackThread],
) -> Value {
    let size_hint = transcript.activity.chars().count();
    let preferred_variant = if size_hint < 3_500 {
        "brief"
    } else {
        "bullets"
    };
    let user_prompt = transcript
        .user_prompt
        .as_deref()
        .unwrap_or("(last user prompt unavailable)");

    let (title_shape, title_rules) = if job.platform == PlatformKind::Codex {
        (
            ",\"title\":\"\"",
            "- title: 3-6 words in Title Case that name the session's current task. No tool names, quotes, leading symbol, or trailing punctuation.\n",
        )
    } else {
        ("", "")
    };

    let (slack_shape, slack_rules) = if slack_threads.is_empty() {
        (String::new(), String::new())
    } else {
        let urls = slack_threads
            .iter()
            .map(|thread| format!("- {}", thread.url))
            .collect::<Vec<_>>()
            .join("\n");
        (
            ",\"slack_threads\":[{\"url\":\"\",\"channel\":\"\",\"author\":\"\"}]".to_string(),
            format!(
                "- slack_threads: one entry for each URL below, unchanged and in the same order. Set channel to its readable channel name and author to the poster's display name only when the transcript identifies them clearly; otherwise use empty strings.\nSlack permalinks:\n{urls}\n"
            ),
        )
    };

    let (pr_block, pr_shape, pr_rules) = if job.prs.is_empty() {
        (String::new(), "", "")
    } else {
        let list = job
            .prs
            .iter()
            .map(|pr| {
                format!(
                    "- {} [{}, {}] :: {}",
                    pr.label,
                    pr.status,
                    if pr.primary { "primary" } else { "secondary" },
                    pr.url
                )
            })
            .collect::<Vec<_>>()
            .join("\n");
        (
            format!("Tracked PRs:\n{list}\n\n"),
            ",\"prs\":[{\"url\":\"\",\"note\":\"\",\"confidence\":\"high|medium|low\"}]",
            "- prs: one entry per tracked PR (same url). note: ≤80 chars on its \
             progress this turn or current blocker. confidence: how confident you \
             are the PR is FINISHED (high = merged/ready, medium = close, low = \
             still cooking or stalled).\n",
        )
    };

    let prompt = format!(
        "Write a Crabigator handoff recap for agent output since the last user-initiated prompt.\n\
         Preferred variant: {preferred_variant}\n\
         Last user prompt, for context only:\n{user_prompt}\n\n\
         {pr_block}Agent activity:\n{}\n\n\
         Return JSON only with this exact shape:\n\
         {{\"variant\":\"brief|bullets\",\"headline\":\"\",\
         \"bullets\":[],\"next_prompt_notes\":[],\"artifacts\":[]{title_shape}{slack_shape}{pr_shape}}}\n\
         Hard length budget — terse > complete sentences:\n\
         - headline: ≤72 chars, no trailing period.\n\
         - bullets: 0-2 items, ≤80 chars each. brief: omit bullets.\n\
         - next_prompt_notes: 0-1 items, ≤80 chars.\n\
         - artifacts: 0-2 items, ≤50 chars each.\n\
         {title_rules}{slack_rules}{pr_rules}Rules:\n\
         - Be terse. Cut filler words. Don't repeat the headline in bullets.\n\
         - Skip code-level details (file names, line numbers, diffs); the Git and Changes widgets cover those.\n\
         - Artifacts = non-code outputs to review (screenshots, logs, URLs, PRs, build reports).\n\
         - If nothing important happened, headline says so plainly and bullets/notes/artifacts are empty.",
        transcript.activity
    );

    // Per-PR notes need extra room beyond the base recap budget.
    let max_tokens = 350
        + 60 * job.prs.len().min(6)
        + 45 * slack_threads.len().min(8)
        + if job.platform == PlatformKind::Codex {
            20
        } else {
            0
        };

    json!({
        "model": job.model,
        "max_tokens": max_tokens,
        "temperature": 0.2,
        "messages": [
            {"role": "user", "content": prompt}
        ]
    })
}

pub(crate) fn call_anthropic(api_key: &str, body: Value) -> Result<String> {
    let api_url = std::env::var("CRABIGATOR_RECAP_API_URL")
        .unwrap_or_else(|_| ANTHROPIC_MESSAGES_URL.to_string());
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .context("Failed to create recap runtime")?;
    runtime.block_on(async {
        let client = reqwest::Client::builder()
            .timeout(std::time::Duration::from_secs(45))
            .build()?;
        let response = client
            .post(api_url)
            .header("x-api-key", api_key)
            .header("anthropic-version", ANTHROPIC_VERSION)
            .json(&body)
            .send()
            .await
            .context("Failed to call Anthropic Messages API")?;

        let status = response.status();
        let text = response.text().await.unwrap_or_default();
        if !status.is_success() {
            anyhow::bail!(
                "Anthropic returned {}: {}",
                status,
                truncate_end(&text, 220)
            );
        }
        extract_anthropic_text(&text)
    })
}

fn extract_anthropic_text(response: &str) -> Result<String> {
    let value: Value = serde_json::from_str(response).context("Anthropic response was not JSON")?;
    let text = value
        .get("content")
        .and_then(|v| v.as_array())
        .into_iter()
        .flatten()
        .filter_map(|block| {
            if block.get("type").and_then(|v| v.as_str()) == Some("text") {
                block.get("text").and_then(|v| v.as_str())
            } else {
                None
            }
        })
        .collect::<Vec<_>>()
        .join("\n");
    if text.trim().is_empty() {
        anyhow::bail!("Anthropic response did not contain text");
    }
    Ok(text)
}

fn parse_recap_response(
    job: &RecapJob,
    response: &str,
    slack_threads: &[SlackThread],
) -> Result<TurnRecap> {
    let json_text = extract_json_object(response).unwrap_or(response);
    let value: Value = serde_json::from_str(json_text).context("Recap response was not JSON")?;
    let variant = match value.get("variant").and_then(|v| v.as_str()) {
        Some("bullets") => RecapVariant::Bullets,
        _ => RecapVariant::Brief,
    };
    let headline = value
        .get("headline")
        .and_then(|v| v.as_str())
        .map(clean_one_line)
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "The agent completed the latest turn.".to_string());
    let bullets = string_array(&value, "bullets", 3);
    let next_prompt_notes = string_array(&value, "next_prompt_notes", 2);
    let artifacts = string_array(&value, "artifacts", 3);
    let pr_notes = pr_note_array(&value);
    let title = if job.platform == PlatformKind::Codex {
        value
            .get("title")
            .and_then(|value| value.as_str())
            .map(clean_generated_title)
            .filter(|title| !title.is_empty())
    } else {
        None
    };
    let slack_threads = merge_slack_metadata(slack_threads, &value);

    Ok(TurnRecap {
        prompt_count: job.prompt_count,
        generated_at: now_unix_ms(),
        title,
        variant,
        headline,
        bullets,
        next_prompt_notes,
        artifacts,
        line_delta: job.line_delta,
        pr_notes,
        slack_threads,
    })
}

/// Apply optional model-derived channel and poster names to the deterministic
/// permalink list. Unknown or invented URLs never enter session state.
fn merge_slack_metadata(threads: &[SlackThread], value: &Value) -> Vec<SlackThread> {
    let candidates = value
        .get("slack_threads")
        .and_then(|value| value.as_array())
        .map(Vec::as_slice)
        .unwrap_or_default();

    threads
        .iter()
        .map(|thread| {
            let candidate = candidates
                .iter()
                .find(|entry| entry.get("url").and_then(|url| url.as_str()) == Some(&thread.url));
            let channel = candidate
                .and_then(|entry| entry.get("channel"))
                .and_then(|channel| channel.as_str())
                .map(clean_one_line)
                .map(|channel| channel.trim_start_matches('#').to_string())
                .filter(|channel| !channel.is_empty())
                .map(|channel| truncate_end(&channel, 60))
                .or_else(|| thread.channel.clone());
            let author = candidate
                .and_then(|entry| entry.get("author"))
                .and_then(|author| author.as_str())
                .map(clean_one_line)
                .filter(|author| !author.is_empty())
                .map(|author| truncate_end(&author, 60));
            SlackThread {
                channel,
                author,
                ..thread.clone()
            }
        })
        .collect()
}

/// The per-PR judgments in a recap response, keeping only well-formed entries.
fn pr_note_array(value: &Value) -> Vec<PrRecapNote> {
    value
        .get("prs")
        .and_then(|v| v.as_array())
        .into_iter()
        .flatten()
        .filter_map(|entry| {
            let url = entry.get("url")?.as_str()?.trim().to_string();
            if url.is_empty() {
                return None;
            }
            let note = entry
                .get("note")
                .and_then(|v| v.as_str())
                .map(clean_one_line)
                .map(|s| truncate_end(&s, 120))
                .unwrap_or_default();
            let confidence = match entry.get("confidence").and_then(|v| v.as_str()) {
                Some(c @ ("high" | "medium" | "low")) => c.to_string(),
                _ => String::new(),
            };
            if note.is_empty() && confidence.is_empty() {
                return None;
            }
            Some(PrRecapNote {
                url,
                note,
                confidence,
            })
        })
        .take(12)
        .collect()
}

