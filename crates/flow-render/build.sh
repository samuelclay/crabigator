#!/bin/bash
# Build the flow scenes for a client. Uses rustup's cargo (the iOS, Android and
# WebAssembly targets need it), by full path so the CLI keeps its own toolchain.
#
#   build.sh wasm                    the dashboard's WebAssembly, written into the Worker
#   build.sh apple PLATFORM ARCHS…   a static library for Xcode (iphoneos or iphonesimulator)
#   build.sh android JNI_LIBS_DIR    shared libraries for the Android app
#
# One-time setup:
#   curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --no-modify-path --profile minimal
#   ~/.cargo/bin/rustup target add wasm32-unknown-unknown aarch64-apple-ios aarch64-apple-ios-sim \
#       aarch64-linux-android armv7-linux-androideabi x86_64-linux-android
#   ~/.cargo/bin/cargo install cargo-ndk   (and the Android NDK, through the SDK manager)
set -euo pipefail
cd "$(dirname "$0")"
CARGO="${CARGO:-$HOME/.cargo/bin/cargo}"
if [ ! -x "$CARGO" ]; then
    echo "error: flow-render needs rustup's cargo at $CARGO (see crates/flow-render/build.sh)" >&2
    exit 1
fi
# A cargo or rustc from another toolchain (Xcode passes its own environment) must not leak in.
unset RUSTC RUSTUP_TOOLCHAIN CARGO_TARGET_DIR
export PATH="$HOME/.cargo/bin:$PATH"

case "${1:-}" in
wasm)
    "$CARGO" build --release --target wasm32-unknown-unknown
    wasm=target/wasm32-unknown-unknown/release/flow_render.wasm
    if command -v wasm-opt >/dev/null; then
        wasm-opt -Os --all-features --strip-debug "$wasm" -o target/flow_render.opt.wasm && wasm=target/flow_render.opt.wasm
    fi
    hash=$(shasum -a 256 "$wasm" | cut -c1-10)
    out=../../workers/crabigator-api/src/assets/flow-wasm.ts
    {
        echo "// Generated by crates/flow-render/build.sh wasm: the flow scenes as WebAssembly,"
        echo "// for the dashboard. The path carries the content hash, so it caches forever."
        echo "export const flowWasmPath = '/assets/flow-render-$hash.wasm';"
        printf "export const flowWasmBase64 = '%s';\n" "$(base64 < "$wasm" | tr -d '\n')"
    } > "$out"
    echo "wrote $out ($(wc -c < "$wasm" | tr -d ' ') bytes)"
    ;;
apple)
    platform="${2:?platform}"; shift 2
    out="$PWD/target/apple/$platform"
    mkdir -p "$out"
    libs=()
    for arch in "$@"; do
        case "$platform/$arch" in
            iphoneos/arm64) target=aarch64-apple-ios ;;
            iphonesimulator/arm64) target=aarch64-apple-ios-sim ;;
            *) echo "error: no flow-render target for $platform/$arch" >&2; exit 1 ;;
        esac
        "$CARGO" build --release --target "$target"
        libs+=("target/$target/release/libflow_render.a")
    done
    if [ "${#libs[@]}" -gt 1 ]; then
        lipo -create "${libs[@]}" -output "$out/libflow_render.a"
    else
        cp "${libs[0]}" "$out/libflow_render.a"
    fi
    echo "built $out/libflow_render.a"
    ;;
android)
    out="${2:?jniLibs directory}"
    ANDROID_HOME="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
    export ANDROID_NDK_HOME="${ANDROID_NDK_HOME:-$(ls -d "$ANDROID_HOME"/ndk/* 2>/dev/null | sort -V | tail -1)}"
    "$CARGO" ndk -t arm64-v8a -t armeabi-v7a -t x86_64 -o "$out" build --release --features android
    ;;
*)
    sed -n 2,13p "$0" >&2
    exit 1
    ;;
esac
